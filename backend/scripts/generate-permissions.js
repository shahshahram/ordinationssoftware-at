// Main
function main() {
  console.log('🔄 Loading schema...');
  const schema = loadSchema();
  
  console.log('📝 Generating Frontend TypeScript types...');
  const frontendCode = generateFrontendTypes(schema);
  fs.writeFileSync(FRONTEND_OUTPUT, frontendCode, 'utf8');
  console.log(`✅ Generated: ${FRONTEND_OUTPUT}`);
  
  console.log('📝 Generating Backend constants...');
  const backendCode = generateBackendConstants(schema);
  fs.writeFileSync(BACKEND_OUTPUT, backendCode, 'utf8');
  console.log(`✅ Generated: ${BACKEND_OUTPUT}`);
  
  console.log('✨ Code generation complete!');
}

if (require.main === module) {
  main();
}

module.exports = { loadSchema, generateFrontendTypes, generateBackendConstants };
