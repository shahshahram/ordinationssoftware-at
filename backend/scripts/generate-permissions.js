#!/usr/bin/env node

/**
 * Permission Code Generator
 * Generiert TypeScript Types und Backend Constants aus permissions.schema.yaml
 */

const fs = require('fs');
const path = require('path');

// Try to load js-yaml (might be in node_modules or as transitive dependency)
let yaml;
try {
  yaml = require('js-yaml');
} catch (error) {
  console.error('Error: js-yaml is required. Please install it with: npm install js-yaml');
  process.exit(1);
}

const SCHEMA_PATH = path.join(__dirname, '../schemas/permissions.schema.yaml');
const FRONTEND_OUTPUT = path.join(__dirname, '../../frontend/src/utils/permissions.generated.ts');
const BACKEND_OUTPUT = path.join(__dirname, '../utils/permissions.generated.js');

// Lade Schema
function loadSchema() {
  try {
    const fileContents = fs.readFileSync(SCHEMA_PATH, 'utf8');
    return yaml.load(fileContents);
  } catch (error) {
    console.error('Error loading schema:', error);
    process.exit(1);
  }
}

// Generiere TypeScript Types für Frontend
function generateFrontendTypes(schema) {
  const { roles, actions, resources } = schema;

  let output = `/**
 * AUTO-GENERATED FILE - DO NOT EDIT MANUALLY
 * Generated from: permissions.schema.yaml
 * Last updated: ${new Date().toISOString()}
 * 
 * This file is automatically generated. Any manual changes will be overwritten.
 */

`;

  // ROLES
  output += `// Rollen-Definitionen\nexport const ROLES = {\n`;
  Object.keys(roles).forEach(roleKey => {
    const role = roles[roleKey];
    const key = roleKey.toUpperCase().replace(/-/g, '_');
    output += `  ${key}: '${roleKey}',\n`;
  });
  output += `} as const;\n\n`;

  output += `export type Role = typeof ROLES[keyof typeof ROLES];\n\n`;

  // ACTIONS
  output += `// Actions (Operationen)\nexport const ACTIONS = {\n`;
  Object.keys(actions).forEach(actionKey => {
    const key = actionKey.toUpperCase().replace(/-/g, '_');
    output += `  ${key}: '${actionKey}',\n`;
  });
  output += `} as const;\n\n`;

  output += `export type Action = typeof ACTIONS[keyof typeof ACTIONS];\n\n`;

  // RESOURCES
  output += `// Resources (Ressourcen-Typen)\nexport const RESOURCES = {\n`;
  Object.keys(resources).forEach(resourceKey => {
    const key = resourceKey.toUpperCase().replace(/-/g, '_');
    output += `  ${key}: '${resourceKey}',\n`;
  });
  output += `} as const;\n\n`;

  output += `export type Resource = typeof RESOURCES[keyof typeof RESOURCES];\n\n`;

  // ROLE_PERMISSIONS
  output += `// Standard-Permissions für jede Rolle\nexport const ROLE_PERMISSIONS: Record<Role, Partial<Record<Resource, readonly Action[]>> & { '*'?: readonly ['*'] }> = {\n`;
  Object.keys(roles).forEach(roleKey => {
    const role = roles[roleKey];
    output += `  [ROLES.${roleKey.toUpperCase().replace(/-/g, '_')}]: {\n`;
    
    if (role.permissions['*'] && role.permissions['*'].includes('*')) {
      output += `    '*': ['*'] as const\n`;
    } else {
      Object.keys(role.permissions).forEach(resource => {
        const actions = role.permissions[resource];
        const resourceKey = resource.toUpperCase().replace(/-/g, '_');
        output += `    [RESOURCES.${resourceKey}]: [${actions.map(a => `ACTIONS.${a.toUpperCase().replace(/-/g, '_')}`).join(', ')}] as const,\n`;
      });
    }
    
    output += `  },\n`;
  });
  output += `} as const;\n\n`;

  // ROLE_HIERARCHY
  output += `// Rollen-Hierarchie\nexport const ROLE_HIERARCHY: Record<Role, readonly Role[]> = {\n`;
  Object.keys(roles).forEach(roleKey => {
    const role = roles[roleKey];
    const level = role.level;
    const lowerRoles = Object.keys(roles)
      .filter(r => roles[r].level < level)
      .map(r => `ROLES.${r.toUpperCase().replace(/-/g, '_')}`);
    
    output += `  [ROLES.${roleKey.toUpperCase().replace(/-/g, '_')}]: [${lowerRoles.join(', ')}] as const,\n`;
  });
  output += `} as const;\n\n`;

  // Helper Types
  output += `// Helper Types\nexport type Permission = \`\${Resource}.\${Action}\`;\n\n`;
  output += `export interface RoleInfo {\n`;
  output += `  role: Role;\n`;
  output += `  label: string;\n`;
  output += `  description: string;\n`;
  output += `  level: number;\n`;
  output += `}\n\n`;

  output += `export const ROLE_INFO: Record<Role, RoleInfo> = {\n`;
  Object.keys(roles).forEach(roleKey => {
    const role = roles[roleKey];
    output += `  [ROLES.${roleKey.toUpperCase().replace(/-/g, '_')}]: {\n`;
    output += `    role: ROLES.${roleKey.toUpperCase().replace(/-/g, '_')},\n`;
    output += `    label: '${role.label}',\n`;
    output += `    description: '${role.description}',\n`;
    output += `    level: ${role.level},\n`;
    output += `  },\n`;
  });
  output += `} as const;\n\n`;

  output += `export default {\n`;
  output += `  ROLES,\n`;
  output += `  ACTIONS,\n`;
  output += `  RESOURCES,\n`;
  output += `  ROLE_PERMISSIONS,\n`;
  output += `  ROLE_HIERARCHY,\n`;
  output += `  ROLE_INFO,\n`;
  output += `};\n`;

  return output;
}

